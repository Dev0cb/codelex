#!/usr/bin/env node
// Rule/property traceability gate (sprint Q4). Fails when a Phase-1 rule ID of GAME_RULES.md, or a global property
// P-GLOBAL-NN of RULE_PROPERTIES.md, has no TAGGED ASSERTION, and keeps the generated table in RULE_PROPERTIES.md fresh.
//
//   node tools/traceability/check.mjs            check (CI): exit 1 on any gap / stale scope / stale table
//   node tools/traceability/check.mjs --write    refresh the generated table in docs/game/RULE_PROPERTIES.md
//   node tools/traceability/check.mjs --json     print the full report as JSON (no table check)
//
// What counts as "a tagged assertion" (documented limits: docs/game/RULE_PROPERTIES.md section 7):
//   * a test (`it` / `test`, also `.each` / `.concurrent` / `.only`) that is NOT skipped (`.skip`, `.todo`,
//     `.skipIf`, `.runIf`, `.fails` never count), in a `*.test.ts` file;
//   * whose own name, an enclosing `describe` name, or a `@covers <IDs>` comment (directly above it or inside its
//     body) cites the ID explicitly: the rule ID itself, or one of its property IDs (`P-CORE-001-c` cites
//     R-CORE-001). Ranges such as `P-GLOBAL-01..08` are NOT expanded;
//   * and whose callback contains at least one real assertion: a matcher call on `expect(<non-literal>)`
//     (`expect(x)` alone, or `expect(true).toBe(true)`, do not count), `assert(...)` / `assert.*(...)`,
//     `fc.assert(...)`, or a direct call to a helper named `expect<Upper>...` / `assert<Upper>...` (weaker: the
//     helper body is not inspected).
// It cannot prove the assertion is about the cited rule, that it can fail, or that a helper really asserts.
//
// Requires `typescript` (root devDependency) to parse tests, so it runs after `pnpm install`.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = process.env.CODELEX_ROOT || join(HERE, '..', '..');
// `typescript` always comes from this repository's install, whatever root is being checked (tests use fixtures).
const require = createRequire(join(HERE, '..', '..', 'package.json'));
const ts = require('typescript');

export const GAME_RULES = 'docs/game/GAME_RULES.md';
export const RULE_PROPERTIES = 'docs/game/RULE_PROPERTIES.md';
export const SCOPE_FILE = 'docs/game/rule-scope.json';
export const BEGIN = '<!-- traceability:begin (generated by tools/traceability/check.mjs --write; do not edit) -->';
export const END = '<!-- traceability:end -->';

const RULE_ID = /\bR-[A-Z]+(?:-[A-Z0-9]+)+\b/g;
const GLOBAL_ID = /\bP-GLOBAL-\d\d\b/g;
const PROP_ID = /\bP-([A-Z]+(?:-[A-Z0-9]+)*?)-([a-z])\b/g;
const SKIP_MODIFIERS = new Set(['skip', 'todo', 'skipIf', 'runIf', 'fails']);
const TEST_ROOTS = new Set(['it', 'test']);
const SUITE_ROOTS = new Set(['describe', 'suite']);

// ---------- spec parsing ----------

/** Rule IDs defined in GAME_RULES.md: bullets `- **R-XXX-NNN** ...` or table rows `| R-XXX-NNN | ...`, in document order. */
export function parseRuleIds(text) {
  const ids = [];
  for (const line of text.split(/\r?\n/)) {
    const m = /^(?:- \*\*|\| )(R-[A-Z]+(?:-[A-Z0-9]+)+)(?:\*\*| \|)/.exec(line);
    if (m && !ids.includes(m[1])) ids.push(m[1]);
  }
  return ids;
}

/** Global property IDs: table rows `| P-GLOBAL-NN | ...` of RULE_PROPERTIES.md. */
export function parseGlobalProperties(text) {
  const ids = [];
  for (const line of text.split(/\r?\n/)) {
    const m = /^\| (P-GLOBAL-\d\d) \|/.exec(line);
    if (m && !ids.includes(m[1])) ids.push(m[1]);
  }
  return ids;
}

/** Property letters defined per rule in section 2 rows `| R-X | (a) ...; (b) ... |` (informational). */
export function parsePropertyLetters(text) {
  const out = new Map();
  for (const line of text.split(/\r?\n/)) {
    const m = /^\| (R-[A-Z]+(?:-[A-Z0-9]+)+) \| (.*)$/.exec(line);
    if (!m) continue;
    const cell = m[2].split(' | ')[0];
    const letters = new Set();
    for (const l of cell.matchAll(/(?:^|[;:.]\s+|\s)\(([a-z])\)(?=[\s'])/g)) letters.add(l[1]);
    out.set(m[1], [...letters].sort());
  }
  return out;
}

/** Validates the scope manifest shape; returns a list of problems (empty = valid). */
export function validateScope(scope, ruleIds) {
  const problems = [];
  if (typeof scope !== 'object' || scope === null) return ['scope: not an object'];
  for (const key of ['outOfScope', 'partial']) {
    const section = scope[key];
    if (typeof section !== 'object' || section === null || Array.isArray(section)) {
      problems.push(`scope.${key}: must be an object keyed by rule ID`);
      continue;
    }
    for (const [id, entry] of Object.entries(section)) {
      if (!ruleIds.includes(id)) problems.push(`scope.${key}.${id}: not a rule ID defined in ${GAME_RULES}`);
      const reason = typeof entry === 'object' && entry !== null ? entry.reason : undefined;
      if (typeof reason !== 'string' || reason.trim().length < 10) {
        problems.push(`scope.${key}.${id}: needs a reason (at least 10 characters)`);
      }
    }
  }
  if (typeof scope.outOfScope === 'object' && typeof scope.partial === 'object') {
    for (const id of Object.keys(scope.partial ?? {})) {
      if (Object.hasOwn(scope.outOfScope ?? {}, id)) problems.push(`scope: ${id} is both outOfScope and partial`);
    }
  }
  return problems;
}

// ---------- test scanning ----------

function listTestFiles(root) {
  const out = [];
  const skip = new Set(['node_modules', 'dist', 'coverage', '.git', '.turbo', '.claude', '.next']);
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      if (skip.has(name)) continue;
      const full = join(dir, name);
      const st = statSync(full);
      if (st.isDirectory()) walk(full);
      else if (/\.test\.(ts|tsx|mts)$/.test(name)) out.push(full);
    }
  };
  for (const top of ['packages', 'services', 'apps']) {
    if (existsSync(join(root, top))) walk(join(root, top));
  }
  return out;
}

function chainInfo(callee) {
  // Unwraps `it.each(table)`, `it.skipIf(c)`, `it.concurrent.only` ... into { root, modifiers }.
  const modifiers = [];
  let node = callee;
  for (;;) {
    if (ts.isCallExpression(node)) node = node.expression;
    else if (ts.isPropertyAccessExpression(node)) {
      modifiers.push(node.name.text);
      node = node.expression;
    } else break;
  }
  return { root: ts.isIdentifier(node) ? node.text : undefined, modifiers };
}

function isLiteralish(node) {
  return (
    ts.isLiteralExpression(node) ||
    node.kind === ts.SyntaxKind.TrueKeyword ||
    node.kind === ts.SyntaxKind.FalseKeyword ||
    node.kind === ts.SyntaxKind.NullKeyword ||
    (ts.isPrefixUnaryExpression(node) && isLiteralish(node.operand)) ||
    (ts.isIdentifier(node) && node.text === 'undefined')
  );
}

/** Real assertions in `body`: { real, helper, vacuous }. */
export function countAssertions(body) {
  let real = 0;
  let helper = 0;
  let vacuous = 0;
  const visit = (node) => {
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      if (ts.isIdentifier(callee)) {
        if (callee.text === 'assert') real += 1;
        else if (/^(expect|assert)[A-Z]/.test(callee.text)) helper += 1;
      } else if (ts.isPropertyAccessExpression(callee)) {
        // fc.assert(...), assert.equal(...)
        const base = callee.expression;
        if (ts.isIdentifier(base) && ((base.text === 'fc' && callee.name.text === 'assert') || base.text === 'assert')) {
          real += 1;
        } else {
          // expect(x).not.toBe(y): walk the member chain down to the `expect(...)` root call.
          let n = callee.expression;
          while (ts.isPropertyAccessExpression(n)) n = n.expression;
          if (
            ts.isCallExpression(n) &&
            ts.isIdentifier(n.expression) &&
            (n.expression.text === 'expect' || n.expression.text === 'expectTypeOf')
          ) {
            const arg = n.arguments[0];
            if (arg !== undefined && isLiteralish(arg)) vacuous += 1;
            else real += 1;
          }
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(body);
  return { real, helper, vacuous };
}

export function idsIn(text) {
  const rules = new Set();
  const globals = new Set();
  const props = new Set();
  for (const m of text.matchAll(RULE_ID)) rules.add(m[0]);
  // Ranges (`P-GLOBAL-01..08`, `P-GLOBAL-01…08`) cite nothing; explicit slash lists (`P-GLOBAL-01/02`) cite each.
  const noRanges = text.replace(/\bP-GLOBAL-\d\d\s*(?:\.\.|…|–|—)\s*(?:P-GLOBAL-)?\d\d\b/g, ' ');
  for (const m of noRanges.matchAll(GLOBAL_ID)) globals.add(m[0]);
  for (const m of noRanges.matchAll(/\bP-GLOBAL-\d\d((?:\/\d\d)+)\b/g)) {
    for (const n of m[1].split('/').filter(Boolean)) globals.add(`P-GLOBAL-${n}`);
  }
  for (const m of text.matchAll(PROP_ID)) props.add(`P-${m[1]}-${m[2]}`);
  return { rules, globals, props };
}

function coversTags(text) {
  // `@covers R-A-001, P-GLOBAL-05` up to the end of the line (inside // or /* */ comments).
  let all = '';
  for (const m of text.matchAll(/@covers\b([^\n]*)/g)) all += ` ${m[1]}`;
  return idsIn(all);
}

/** Scans one test file source; returns the tests found (skipped ones included, flagged). */
export function scanSource(fileName, sourceText) {
  const sf = ts.createSourceFile(fileName, sourceText, ts.ScriptTarget.Latest, true);
  const tests = [];
  const visit = (node, ancestors) => {
    if (ts.isCallExpression(node)) {
      const { root, modifiers } = chainInfo(node.expression);
      const isTest = root !== undefined && TEST_ROOTS.has(root);
      const isSuite = root !== undefined && SUITE_ROOTS.has(root);
      if ((isTest || isSuite) && node.arguments.length >= 2) {
        const nameNode = node.arguments[0];
        const name = nameNode !== undefined ? nameNode.getText(sf) : '';
        const callback = node.arguments.find((a) => ts.isArrowFunction(a) || ts.isFunctionExpression(a));
        const skipped = modifiers.some((m) => SKIP_MODIFIERS.has(m));
        const leading = (ts.getLeadingCommentRanges(sourceText, node.getFullStart()) ?? [])
          .map((r) => sourceText.slice(r.pos, r.end))
          .join('\n');
        if (isSuite) {
          const next = [...ancestors, { name, skipped }];
          if (callback !== undefined) ts.forEachChild(callback, (c) => visit(c, next));
          return;
        }
        const bodyText = callback !== undefined ? callback.getText(sf) : '';
        const own = idsIn(name);
        const comments = coversTags(`${leading}\n${bodyText}`);
        const inherited = idsIn(ancestors.map((a) => a.name).join('\n'));
        const assertions = callback !== undefined ? countAssertions(callback) : { real: 0, helper: 0, vacuous: 0 };
        tests.push({
          file: fileName,
          name: name.replace(/^['"`]|['"`]$/g, ''),
          skipped: skipped || ancestors.some((a) => a.skipped),
          hasCallback: callback !== undefined,
          rules: new Set([...own.rules, ...comments.rules, ...inherited.rules]),
          globals: new Set([...own.globals, ...comments.globals, ...inherited.globals]),
          props: new Set([...own.props, ...comments.props, ...inherited.props]),
          // `P-CORE-001-c` cites rule R-CORE-001 (RULE_PROPERTIES: property x of R-<AREA>-<NNN> is P-<AREA>-<NNN>-x).
          propRules: new Set(
            [...own.props, ...comments.props, ...inherited.props].map((p) => p.replace(/^P-/, 'R-').replace(/-[a-z]$/, '')),
          ),
          assertions,
          asserts: assertions.real + assertions.helper > 0,
        });
        return;
      }
    }
    ts.forEachChild(node, (c) => visit(c, ancestors));
  };
  visit(sf, []);
  return tests;
}

export function scanTests(root) {
  const tests = [];
  for (const file of listTestFiles(root)) {
    const rel = relative(root, file).split(sep).join('/');
    tests.push(...scanSource(rel, readFileSync(file, 'utf8')));
  }
  return tests;
}

// ---------- analysis ----------

export function analyze({ ruleIds, globalIds, letters, scope, tests }) {
  const live = tests.filter((t) => !t.skipped && t.hasCallback);
  const problems = [];
  const knownRules = new Set(ruleIds);
  const knownGlobals = new Set(globalIds);

  const rows = ruleIds.map((id) => {
    const out = scope.outOfScope?.[id];
    const partial = scope.partial?.[id];
    const tagged = live.filter((t) => t.rules.has(id) || t.propRules.has(id));
    const asserting = tagged.filter((t) => t.asserts);
    const mentionOnly = tagged.filter((t) => !t.asserts);
    const vacuousOnly = mentionOnly.filter((t) => t.assertions.vacuous > 0);
    const status = out !== undefined ? 'out-of-scope' : asserting.length > 0 ? 'covered' : 'GAP';
    const propId = `P-${id.slice(2)}-`;
    const cited = new Set();
    for (const t of asserting) for (const p of t.props) if (p.startsWith(propId)) cited.add(p.slice(propId.length));
    const defined = letters.get(id) ?? [];
    return {
      id,
      status,
      reason: out?.reason,
      partial: partial?.reason,
      files: [...new Set(asserting.map((t) => t.file))].sort(),
      assertingTests: asserting.length,
      mentionOnly: mentionOnly.map((t) => `${t.file}: ${t.name}`),
      vacuous: vacuousOnly.length,
      defined,
      cited: [...cited].sort(),
      uncited: defined.filter((l) => !cited.has(l)),
    };
  });
  const globals = globalIds.map((id) => {
    const asserting = live.filter((t) => t.globals.has(id) && t.asserts);
    const mention = live.filter((t) => t.globals.has(id) && !t.asserts);
    return {
      id,
      status: asserting.length > 0 ? 'covered' : 'GAP',
      files: [...new Set(asserting.map((t) => t.file))].sort(),
      mentionOnly: mention.map((t) => `${t.file}: ${t.name}`),
    };
  });

  for (const row of rows) {
    if (row.status === 'GAP') {
      const hint = row.mentionOnly.length > 0 ? ` (cited without an assertion in: ${row.mentionOnly.join('; ')})` : '';
      problems.push(`${row.id}: Phase-1 rule has no tagged assertion${hint}`);
    }
  }
  for (const g of globals) {
    if (g.status === 'GAP') {
      const hint = g.mentionOnly.length > 0 ? ` (cited without an assertion in: ${g.mentionOnly.join('; ')})` : '';
      problems.push(`${g.id}: global property has no tagged assertion${hint}`);
    }
  }
  // Typos and stale tags: a cited ID that the specs do not define.
  for (const t of tests) {
    for (const id of t.rules) {
      if (!knownRules.has(id)) problems.push(`${t.file}: "${t.name}" cites unknown rule ID ${id}`);
    }
    for (const id of t.globals) {
      if (!knownGlobals.has(id)) problems.push(`${t.file}: "${t.name}" cites unknown global property ${id}`);
    }
  }
  return { rows, globals, problems, testsScanned: tests.length, skippedTests: tests.filter((t) => t.skipped).length };
}

// ---------- rendering ----------

const cell = (s) => s.replace(/\|/g, '\\|');

export function renderTable(report) {
  const lines = [];
  const covered = report.rows.filter((r) => r.status === 'covered').length;
  const out = report.rows.filter((r) => r.status === 'out-of-scope').length;
  const gaps = report.rows.filter((r) => r.status === 'GAP').length;
  lines.push(
    `Rule IDs in GAME_RULES.md: ${String(report.rows.length)}; covered by a tagged assertion: ${String(covered)}; out of Phase-1 scope: ${String(out)}; gaps: ${String(gaps)}.`,
  );
  lines.push('');
  lines.push('| Rule | Status | Tagged assertions in | Properties cited / not cited (informational) | Note |');
  lines.push('|---|---|---|---|---|');
  for (const r of report.rows) {
    const files = r.files.length > 0 ? r.files.map((f) => `\`${f}\``).join('<br>') : '—';
    const letters =
      r.defined.length === 0
        ? '—'
        : `${r.cited.length > 0 ? r.cited.join(',') : '—'} / ${r.uncited.length > 0 ? r.uncited.join(',') : '—'}`;
    const note = r.reason !== undefined ? `Out of scope: ${r.reason}` : (r.partial ?? '');
    lines.push(`| ${r.id} | ${r.status} | ${cell(files)} | ${letters} | ${cell(note)} |`);
  }
  lines.push('');
  lines.push('| Global property | Status | Tagged assertions in |');
  lines.push('|---|---|---|');
  for (const g of report.globals) {
    const files = g.files.length > 0 ? g.files.map((f) => `\`${f}\``).join('<br>') : '—';
    lines.push(`| ${g.id} | ${g.status} | ${cell(files)} |`);
  }
  return lines.join('\n');
}

export function stripTable(docText) {
  const start = docText.indexOf(BEGIN);
  const end = docText.indexOf(END);
  return start === -1 || end === -1 || end < start ? docText : docText.slice(0, start) + docText.slice(end + END.length);
}

export function applyTable(docText, table) {
  const block = `${BEGIN}\n${table}\n${END}`;
  const start = docText.indexOf(BEGIN);
  const end = docText.indexOf(END);
  if (start === -1 || end === -1 || end < start) return undefined;
  return docText.slice(0, start) + block + docText.slice(end + END.length);
}

// ---------- CLI ----------

export function run(root = ROOT, argv = process.argv.slice(2)) {
  const read = (p) => readFileSync(join(root, p), 'utf8');
  const ruleIds = parseRuleIds(read(GAME_RULES));
  const propsFull = read(RULE_PROPERTIES);
  // The generated block is output, never input: strip it before parsing the spec tables.
  const propsText = stripTable(propsFull);
  const scope = JSON.parse(read(SCOPE_FILE));
  const scopeProblems = validateScope(scope, ruleIds);
  const report = analyze({
    ruleIds,
    globalIds: parseGlobalProperties(propsText),
    letters: parsePropertyLetters(propsText),
    scope: scopeProblems.length === 0 ? scope : { outOfScope: {}, partial: {} },
    tests: scanTests(root),
  });
  const problems = [...scopeProblems, ...report.problems];
  if (argv.includes('--json')) return { code: problems.length > 0 ? 1 : 0, out: JSON.stringify(report, null, 2), problems };

  const table = renderTable(report);
  const refreshed = applyTable(propsFull, table);
  if (refreshed === undefined) problems.push(`${RULE_PROPERTIES}: traceability markers not found`);
  else if (argv.includes('--write')) {
    if (refreshed !== propsFull) writeFileSync(join(root, RULE_PROPERTIES), refreshed);
  } else if (refreshed !== propsFull) {
    problems.push(`${RULE_PROPERTIES}: generated traceability table is stale; run \`pnpm traceability:write\``);
  }
  const summary = `traceability: ${String(report.rows.length)} rule IDs, ${String(report.globals.length)} global properties, ${String(report.testsScanned)} tests scanned (${String(report.skippedTests)} skipped, never counted)`;
  return { code: problems.length > 0 ? 1 : 0, out: summary, problems };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { code, out, problems } = run();
  console.log(out);
  for (const p of problems) console.error(`FAIL ${p}`);
  process.exit(code);
}
