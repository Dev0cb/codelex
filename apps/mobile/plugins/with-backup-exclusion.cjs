// Expo config plugin: keep CODELEX app data out of OS backups (threat model e-1.5-s1-persistence-match-log, TM-03).
// The on-device match log, its snapshot and the "New to you" history (and, from slice S6, the analytics queue and
// the install id) must never leave the phone without a tap (E-1.5 privacy notes; spec: "match data stays on device").
//
// - Android: `android.allowBackup: false` (app.json) stops cloud backup; Android 12+ still copies app data in a
//   device-to-device transfer unless `dataExtractionRules` exclude it, so this plugin adds rules that exclude every
//   domain from both cloud backup and device transfer, and `fullBackupContent="false"` for Android 11 and lower.
// - iOS: the app's data directory `<Documents>/codelex-data` (src/persistence/device-fs.ts) gets the
//   `isExcludedFromBackup` resource value at every launch, from the AppDelegate, before any JavaScript runs.
const { mkdirSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

/** Must equal DATA_DIR in src/persistence/device-fs.ts (checked by a test). */
const DATA_DIR = 'codelex-data';
const RULES_NAME = 'codelex_data_extraction_rules';
// Every domain of the data-extraction-rules format, credential-protected and device-protected storage alike.
const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

const exclusions = (indent) =>
  DOMAINS.map((domain) => `${indent}<exclude domain="${domain}" path="." />`).join('\n');

const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-exclusion.cjs (threat model TM-03). Do not edit. -->
<data-extraction-rules>
  <cloud-backup>
${exclusions('    ')}
  </cloud-backup>
  <device-transfer>
${exclusions('    ')}
  </device-transfer>
</data-extraction-rules>
`;

/** Sets the backup attributes on the manifest's <application> (pure, for tests). */
function applyAndroidBackupRules(manifest) {
  const application = manifest.manifest.application?.[0];
  if (application === undefined)
    throw new Error('with-backup-exclusion: no <application> in the manifest');
  application.$ = {
    ...application.$,
    'android:allowBackup': 'false',
    'android:fullBackupContent': 'false',
    'android:dataExtractionRules': `@xml/${RULES_NAME}`,
  };
  return manifest;
}

const MARK = 'codelex-backup-exclusion';
const SWIFT_HELPER = `
// @generated begin ${MARK} (plugins/with-backup-exclusion.cjs, threat model TM-03). Do not edit.
enum CodelexBackupExclusion {
  /// Creates <Documents>/${DATA_DIR} if needed and excludes it from iCloud and computer backups.
  static func apply() {
    let manager = FileManager.default
    guard let documents = manager.urls(for: .documentDirectory, in: .userDomainMask).first else { return }
    var directory = documents.appendingPathComponent("${DATA_DIR}", isDirectory: true)
    try? manager.createDirectory(at: directory, withIntermediateDirectories: true)
    var values = URLResourceValues()
    values.isExcludedFromBackup = true
    try? directory.setResourceValues(values)
  }
}
// @generated end ${MARK}
`;
const LAUNCH = /(didFinishLaunchingWithOptions launchOptions:[^)]*\)\s*->\s*Bool\s*\{\n)/;

/** Adds the exclusion call at the start of launch and the helper at the end of the Swift AppDelegate (pure). */
function applyIosBackupExclusion(source) {
  if (source.includes(MARK)) return source;
  if (!LAUNCH.test(source)) {
    throw new Error(
      'with-backup-exclusion: AppDelegate.swift has no didFinishLaunchingWithOptions to patch',
    );
  }
  const withImport = /^import Foundation$/m.test(source) ? source : `import Foundation\n${source}`;
  return `${withImport.replace(LAUNCH, `$1    CodelexBackupExclusion.apply() // ${MARK}\n`)}${SWIFT_HELPER}`;
}

function withBackupExclusion(config) {
  // Loaded here, not at the top: the pure functions below are unit-tested without the prebuild toolchain.
  const { withAndroidManifest, withAppDelegate, withDangerousMod } = require('expo/config-plugins');
  let next = withAndroidManifest(config, (mod) => {
    mod.modResults = applyAndroidBackupRules(mod.modResults);
    return mod;
  });
  next = withDangerousMod(next, [
    'android',
    (mod) => {
      const dir = join(mod.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      mkdirSync(dir, { recursive: true });
      writeFileSync(join(dir, `${RULES_NAME}.xml`), DATA_EXTRACTION_RULES_XML);
      return mod;
    },
  ]);
  return withAppDelegate(next, (mod) => {
    if (mod.modResults.language !== 'swift') {
      throw new Error('with-backup-exclusion: only a Swift AppDelegate is supported');
    }
    mod.modResults.contents = applyIosBackupExclusion(mod.modResults.contents);
    return mod;
  });
}

module.exports = withBackupExclusion;
module.exports.DATA_DIR = DATA_DIR;
module.exports.DATA_EXTRACTION_RULES_XML = DATA_EXTRACTION_RULES_XML;
module.exports.applyAndroidBackupRules = applyAndroidBackupRules;
module.exports.applyIosBackupExclusion = applyIosBackupExclusion;
